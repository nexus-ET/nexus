export function processNodeClasses(opts: {
  active: boolean;
  process: boolean;
  nestParent: boolean;
  nested: boolean;
}): string {
  const { active, process, nestParent, nested } = opts;
  if (nested && active) {
    return `${nodeBase} h-[3.7rem] max-h-[3.7rem] min-h-[3.7rem] w-[8.7rem] min-w-[8.7rem] max-w-[8.7rem] border-teal-800 bg-teal-300 px-[7px] py-[5px] shadow-[0_0_0_2px_rgba(15,118,110,0.28)] hover:border-teal-800 hover:bg-teal-300`;
  }
  if (nested) {
    return `${nodeBase} h-[3.1rem] max-h-[3.1rem] min-h-[3.1rem] w-[7.5rem] min-w-[7.5rem] max-w-[7.5rem] border-teal-400 bg-teal-100 px-1.5 py-1 hover:border-teal-500 hover:bg-teal-200`;
  }
  if (nestParent && active) {
    return `${nodeBase} h-[4.2rem] max-h-[4.2rem] min-h-[4.2rem] w-[11.4rem] min-w-[11.4rem] max-w-[11.4rem] border-accent bg-accent px-2.5 py-[7px] shadow-[0_0_0_2px_rgba(50,47,134,0.28)] hover:border-[#2b2875] hover:bg-[#2b2875]`;
  }
  if (nestParent) {
    return `${nodeBase} h-[3.4rem] max-h-[3.4rem] min-h-[3.4rem] w-[8.4rem] min-w-[8.4rem] max-w-[8.4rem] border-accent bg-accent px-[7px] py-[5px] hover:border-[#2b2875] hover:bg-[#2b2875]`;
  }
  if (active) {
    return `${nodeBase} h-[4.2rem] max-h-[4.2rem] min-h-[4.2rem] w-[11.4rem] min-w-[11.4rem] max-w-[11.4rem] border-accent bg-[#dfe3ff] px-2.5 py-[7px] shadow-[0_0_0_2px_rgba(50,47,134,0.2)] hover:border-accent hover:bg-[#dfe3ff]`;
  }
  if (process) {
    return `${nodeBase} h-[4.2rem] max-h-[4.2rem] min-h-[4.2rem] w-[10.8rem] min-w-[10.8rem] max-w-[10.8rem] border-accent bg-accent px-2.5 py-[7px] hover:border-[#2b2875] hover:bg-[#2b2875]`;
  }
  return `${nodeBase} h-[3.4rem] max-h-[3.4rem] min-h-[3.4rem] w-[8.4rem] min-w-[8.4rem] max-w-[8.4rem] border-slate-300 bg-slate-200 px-[7px] py-[5px] hover:border-slate-400 hover:bg-[#d8dee8]`;
}

export function processCodeClasses(opts: {
  active: boolean;
  process: boolean;
  nestParent: boolean;
  nested: boolean;
}): string {
  const { active, process, nestParent, nested } = opts;
  const base =
    'm-0 w-full overflow-hidden text-ellipsis whitespace-nowrap text-center font-extrabold uppercase tracking-widest';
  if (nested && active) return `${base} text-[9px] tracking-[0.08em] text-teal-900`;
  if (nested) return `${base} text-[9px] tracking-[0.08em] text-teal-700`;
  if (process || nestParent) return `${base} text-[11px] text-white opacity-100`;
  if (active) return `${base} text-[11px] text-accent opacity-100`;
  return `${base} text-[10px] text-slate-500`;
}

export function processTitleClasses(opts: {
  active: boolean;
  process: boolean;
  nestParent: boolean;
  nested: boolean;
}): string {
  const { active, process, nestParent, nested } = opts;
  const base =
    'mt-0.5 line-clamp-1 w-full overflow-hidden break-words text-center font-bold leading-tight';
  if (nested && active) return `${base} text-[11px] text-teal-900`;
  if (nested) return `${base} text-[11px] text-teal-800`;
  if (nestParent) {
    return `${base} ${active ? 'line-clamp-2 text-[13px]' : 'text-xs'} text-white`;
  }
  if (process) return `${base} line-clamp-2 text-[13px] text-white`;
  if (active) return `${base} line-clamp-2 text-[13px] text-slate-900`;
  return `${base} text-xs text-slate-600`;
}

